-- Give deployment preflight a read-only contract for database behavior that
-- cannot be proven by selecting tables and columns alone.
create or replace function public.magpie_schema_capabilities()
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
  select jsonb_build_object(
    'schema', 'magpie.supabase_capabilities.v1',
    'features', jsonb_build_object(
      'atomic_location_lifecycle', true
    )
  );
$$;
