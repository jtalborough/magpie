-- Data imports preserve existing local IDs so printed QR labels and undo/event
-- references remain valid. Explicit identity inserts do not advance sequences,
-- so the importer calls this once after all rows are present.
create or replace function public.advance_magpie_identity_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  seq_name text;
  max_id bigint;
  table_name text;
begin
  foreach table_name in array array[
    'items',
    'photos',
    'hardware_bindings',
    'placement_rules',
    'size_rules',
    'agent_examples',
    'repository_events',
    'assistant_interactions',
    'voice_attempts'
  ]
  loop
    seq_name := pg_get_serial_sequence('public.' || table_name, 'local_id');
    execute format('select max(local_id) from public.%I', table_name) into max_id;
    if max_id is null then
      perform setval(seq_name::regclass, 1, false);
    else
      perform setval(seq_name::regclass, max_id, true);
    end if;
  end loop;
end;
$$;

revoke all on function public.advance_magpie_identity_sequences() from public;
revoke all on function public.advance_magpie_identity_sequences() from anon;
revoke all on function public.advance_magpie_identity_sequences() from authenticated;
grant execute on function public.advance_magpie_identity_sequences() to service_role;

create or replace function public.magpie_workspace_counts(target_workspace_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'locations', (select count(*) from public.locations where workspace_id = target_workspace_id),
    'items', (select count(*) from public.items where workspace_id = target_workspace_id),
    'item_aliases', (
      select count(*)
      from public.item_aliases a
      join public.items i on i.id = a.item_id
      where i.workspace_id = target_workspace_id
    ),
    'inventory_entries', (select count(*) from public.inventory_entries where workspace_id = target_workspace_id),
    'photos', (select count(*) from public.photos where workspace_id = target_workspace_id),
    'inventory_review_photos', (select count(*) from public.inventory_review_photos where workspace_id = target_workspace_id),
    'hardware_bindings', (select count(*) from public.hardware_bindings where workspace_id = target_workspace_id),
    'placement_rules', (select count(*) from public.placement_rules where workspace_id = target_workspace_id),
    'size_rules', (select count(*) from public.size_rules where workspace_id = target_workspace_id),
    'agent_examples', (select count(*) from public.agent_examples where workspace_id = target_workspace_id),
    'assistant_interactions', (select count(*) from public.assistant_interactions where workspace_id = target_workspace_id),
    'voice_attempts', (select count(*) from public.voice_attempts where workspace_id = target_workspace_id),
    'repository_events', (select count(*) from public.repository_events where workspace_id = target_workspace_id)
  );
$$;

revoke all on function public.magpie_workspace_counts(uuid) from public;
revoke all on function public.magpie_workspace_counts(uuid) from anon;
revoke all on function public.magpie_workspace_counts(uuid) from authenticated;
grant execute on function public.magpie_workspace_counts(uuid) to service_role;
