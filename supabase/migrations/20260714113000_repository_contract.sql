-- Complete the cloud schema needed by Magpie's repository contract.
--
-- UUID primary keys remain the cloud identity. Workspace-scoped local IDs keep
-- existing QR codes, API payloads, agent plans, and undo records stable while
-- the Pi, web app, and future native clients share the same data.

alter table public.items
  add column local_id bigint generated by default as identity;
create unique index items_workspace_local_id_idx
  on public.items(workspace_id, local_id);

alter table public.locations
  add column grid jsonb not null default '{}'::jsonb,
  add column cell_col integer,
  add column cell_row integer,
  add column cell_w integer not null default 1,
  add column cell_h integer not null default 1,
  add column light_target text,
  add column light_indexes integer[] not null default '{}';

alter table public.locations drop constraint if exists locations_type_check;
alter table public.locations
  add constraint locations_type_check check (
    type in (
      'home', 'room', 'area', 'cabinet', 'drawer', 'shelf', 'shelf-unit',
      'box', 'pouch', 'bin', 'cell', 'tote', 'rack', 'locker', 'storage_unit'
    )
  );

alter table public.inventory_entries
  add column review_reason text not null default '';

-- A photo is uploaded before the agent knows its destination, so targets must
-- be nullable. Explicit target columns make PostgREST joins and RLS direct.
alter table public.photos
  alter column object_type drop not null,
  alter column object_id drop not null,
  add column local_id bigint generated by default as identity,
  add column filename text not null default '',
  add column item_id uuid references public.items(id) on delete set null,
  add column location_id uuid references public.locations(id) on delete set null;
create unique index photos_workspace_local_id_idx
  on public.photos(workspace_id, local_id);
create index photos_workspace_item_idx
  on public.photos(workspace_id, item_id);
create index photos_workspace_location_idx
  on public.photos(workspace_id, location_id);

